export const generateAIResponse = async (prompt: string): Promise<string> => {
  if (!apiKey) {
    return "API Key not found. Please check your environment configuration.";
  }

  try {
    const response = await ai.models.generateContent({
      model: 'gemini-2.5-flash',
      contents: prompt,
      config: {
        systemInstruction: SYSTEM_INSTRUCTION,
      }
    });
    return response.text || "抱歉，我现在无法回答这个问题。";
  } catch (error) {
    console.error("Gemini API Error:", error);
    return "网络连接异常，请稍后再试。";
  }
};

export interface FileData {
  inlineData: {
    mimeType: string;
    data: string; // base64
  };
}

export const evaluateQualification = async (
  files: FileData[], 
  profile: CustomerProfile,
  product: LoanProduct | null
): Promise<string> => {
  if (!apiKey) {
    return "API Key not found.";
  }

  const productName = product ? product.name : "未指定产品";
  
  const promptText = `
    请作为银行风控审核员，对该客户进行准入资格初审。
    
    【申请意向】
    拟申请产品：${productName}
    拟申请金额：${profile.loanAmount} 元
    贷款用途：${profile.loanPurpose}
    
    【客户填报信息】
    - 年龄：${profile.age} 周岁
    - 职业/身份：${profile.occupation}
    - 年收入：${profile.annualIncome} 元
    - 住房情况：${profile.housingStatus}
    - 客户自述征信情况：${profile.overdueHistory || "无"}

    【附件分析】
    我已上传客户的征信报告或银行流水图片（如有）。
    
    【任务要求】
    请结合上方的《系统指令》中该产品具体的准入规则（如年龄限制、职业要求、逾期次数限制M3/6次、信用类产品的A-评级/盈利要求等），进行综合判定。
    
    请输出一份【准入预审报告】：
    1. **判定结果**：建议通过 / 建议拒贷 / 需补充资料 / 需人工复核
    2. **关键指标核对**：
       - 年龄是否符合？
       - 职业/经营主体是否符合？（如吉商贷信用类需核实经营年限、盈利情况、实控人身份）
       - 征信记录是否超标？（结合图片内容和自述）
       - 流水/收入是否支撑还款？
       - 多头借贷检查（如吉商贷信用类他行不超过2家）
    3. **风险提示**：发现的具体硬伤或疑点。
    4. **下一步建议**。（如吉商贷信用类，提醒准备电子税局账号密码）
  `;

  try {
    const response = await ai.models.generateContent({
      model: 'gemini-2.5-flash',
      contents: {
        parts: [
          { text: promptText },
          ...files
        ]
      },
      config: {
        systemInstruction: SYSTEM_INSTRUCTION,
      }
    });
    return response.text || "无法生成评估报告。";
  } catch (error) {
    console.error("Gemini Vision Error:", error);
    return "图片分析失败，请确保图片清晰或稍后再试。";
  }
};